                        <h2 style="color: #1a1a2e; font-size: 22px; margin: 30px 0 20px 0; border-bottom: 2px solid #2ecc71; padding-bottom: 8px;">&#128247; HEIC photos now upload on the web</h2>

                        <p>If you've ever tried to upload an iPhone photo on the website and watched it silently fail, that's fixed. Apple's native <strong>.HEIC</strong> format now uploads directly at <a href="https://openlittermap.com/upload" target="_blank">openlittermap.com/upload</a> &mdash; it's accepted, converted automatically, and your GPS location is preserved.</p>

                        <p>HEIC was already working in the mobile app; now the website works too. If an upload still gives you trouble, tell us &mdash; that feedback is exactly what got this fixed.</p>

